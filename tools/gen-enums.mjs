// Generates packages/shared/src/enums/generated.ts from packages/db/prisma/schema.prisma (enums mirror Postgres enums 1:1).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const s = readFileSync('packages/db/prisma/schema.prisma', 'utf8');
const out = ['// GENERATED by tools/gen-enums.mjs from packages/db/prisma/schema.prisma — do not edit by hand.'];
const names = [];
for (const m of s.matchAll(/^enum\s+(\w+)\s*\{([^}]*)\}/gm)) {
  const values = m[2].split(/\r?\n/).map((l) => l.replace(/\/\/.*$/, '').trim()).filter(Boolean).map((l) => l.split(/\s+/)[0]);
  names.push(m[1]);
  out.push(`export const ${m[1]} = { ${values.map((v) => `${/^[a-zA-Z_$][\w$]*$/.test(v) ? v : JSON.stringify(v)}: '${v}'`).join(', ')} } as const;`);
  out.push(`export type ${m[1]} = (typeof ${m[1]})[keyof typeof ${m[1]}];`);
  out.push(`export const ${m[1]}Values = Object.values(${m[1]}) as [${m[1]}, ...${m[1]}[]];`);
}
mkdirSync('packages/shared/src/enums', { recursive: true });
writeFileSync('packages/shared/src/enums/generated.ts', out.join('\n') + '\n');
// tenant models: every model with a workspaceId field
const tenant = [];
for (const m of s.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) if (/^\s*workspaceId\s+String\b(?!\?)/m.test(m[2])) tenant.push(m[1]);
writeFileSync('packages/db/src/tenant-models.ts', `// GENERATED by tools/gen-enums.mjs — every model with a NOT NULL workspaceId.\nexport const TENANT_MODELS: ReadonlySet<string> = new Set(${JSON.stringify(tenant)});\n`);
console.log('enums', names.length, 'tenant models', tenant.length);
