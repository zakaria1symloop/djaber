// Generates packages/shared/src/errors/{codes.ts,messages.fr|ar|en.json,aliases.ts} from docs/specs/11-error-catalogue.md.
// 11 is the single source of error codes (CLAUDE.md rule 8). Re-run after editing 11: `node tools/gen-errors.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync('docs/specs/11-error-catalogue.md', 'utf8').split(/\r?\n/);
const codes = {}; const fr = {}; const ar = {}; const en = {}; const warnings = {}; const skipped = [];
let section = '';
for (const line of src) {
  if (line.startsWith('#')) { section = line; continue; }
  if (!line.startsWith('|')) continue;
  const cells = line.split('|').slice(1, -1).map((c) => c.trim());
  if (cells.length < 5) continue;
  const m0 = /^(\d{3}|0|—)/.exec(cells[0]);
  const codeCell = /`([A-Z][A-Z0-9_]+)`\s*(\{[^}]*\})?/.exec(cells[1] ?? '');
  if (m0 && codeCell) {
    const code = codeCell[1]; const status = m0[1] === '—' ? 0 : Number(m0[1]);
    const params = codeCell[2] ? codeCell[2].replace(/[{}]/g, '').split(',').map((s) => s.trim()).filter(Boolean) : [];
    if (codes[code]) continue;
    codes[code] = { status: status === 0 ? 0 : status, params };
    fr[code] = cells[2]; ar[code] = cells[3]; en[code] = cells[4];
    continue;
  }
  // warnings tables: | `CODE` {params} | fr | ar | en | ...
  const w = /^`([A-Z][A-Z0-9_]+)`\s*(\{[^}]*\})?/.exec(cells[0] ?? '');
  if (w && /warning/i.test(section)) { warnings[w[1]] = true; fr[w[1]] ??= cells[1]; ar[w[1]] ??= cells[2]; en[w[1]] ??= cells[3]; continue; }
  if (/`[A-Z][A-Z0-9_]{3,}`/.test(line) && !/^\|\s*(HTTP|---)/.test(line)) skipped.push(line.slice(0, 110));
}
// aliases (11 §13): `ALIAS` (…) | `CANONICAL` …
const aliases = {};
{ let in13 = false; for (const line of src) { if (line.startsWith('## 13')) in13 = true; else if (line.startsWith('## ') ) in13 = false; if (!in13 || !line.startsWith('|')) continue; const c = line.split('|').slice(1, -1).map((x) => x.trim()); const a = /^`([A-Z][A-Z0-9_]+)`/.exec(c[0] ?? ''); const b = /`([A-Z][A-Z0-9_]+)/.exec(c[1] ?? ''); if (a && b && a[1] !== b[1]) aliases[a[1]] = b[1]; } }
writeFileSync('packages/shared/src/errors/aliases.ts', `// GENERATED from 11 §13 — aliases must never be used in code; this file exists only to detect them.
export const ERROR_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};
`);
const sorted = Object.keys(codes).sort();
writeFileSync('packages/shared/src/errors/codes.ts',
`// GENERATED by tools/gen-errors.mjs from docs/specs/11-error-catalogue.md — do not edit by hand.
export const ERROR_CODES = {
${sorted.map((c) => `  ${c}: { status: ${codes[c].status}, params: ${JSON.stringify(codes[c].params)} },`).join('\n')}
} as const;
export type ErrorCode = keyof typeof ERROR_CODES;
export const WARNING_CODES = ${JSON.stringify(Object.keys(warnings).sort())} as const;
export type WarningCode = (typeof WARNING_CODES)[number];
export const isErrorCode = (c: string): c is ErrorCode => c in ERROR_CODES;
`);
const dump = (o) => JSON.stringify(Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]])), null, 2) + '\n';
writeFileSync('packages/shared/src/errors/messages.fr.json', dump(fr));
writeFileSync('packages/shared/src/errors/messages.ar.json', dump(ar));
writeFileSync('packages/shared/src/errors/messages.en.json', dump(en));
console.log('codes', sorted.length, 'warnings', Object.keys(warnings).length, 'skipped', skipped.length);
if (process.argv.includes('--verbose')) console.log(skipped.join('\n'));
